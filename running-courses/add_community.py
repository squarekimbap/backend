import json, pathlib, subprocess, time, urllib.parse

ROOT = pathlib.Path(__file__).parent

def env_key(name):
    for line in (ROOT.parent / '.env').read_text().splitlines():
        if line.startswith(name + '='):
            return line.split('=', 1)[1].strip()
    raise SystemExit(f'.env에 {name} 없음')

TOUR = env_key('TOUR_API_KEY')

def photo_of(keyword, city_token):
    """TourAPI 키워드검색 → (photo, photoTitle) 또는 (None, None)."""
    q = urllib.parse.urlencode({
        'serviceKey': TOUR, 'MobileOS': 'ETC', 'MobileApp': 'tour-api',
        '_type': 'json', 'numOfRows': 10, 'pageNo': 1, 'keyword': keyword})
    out = subprocess.run(['curl', '-s', '-m', '15',
                          'https://apis.data.go.kr/B551011/KorService2/searchKeyword2?' + q],
                         capture_output=True).stdout
    try:
        items = json.loads(out)['response']['body'].get('items') or {}
        items = items.get('item') or []
        if isinstance(items, dict):
            items = [items]
    except Exception:
        return None, None
    for it in items:
        if city_token in it.get('addr1', '') and it.get('firstimage'):
            return it['firstimage'], it.get('title')
    return None, None

