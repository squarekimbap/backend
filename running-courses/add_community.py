for fname, items in by_file.items():
    path = ROOT / 'data' / fname
    raw = json.load(open(path))
    was_dict = isinstance(raw, dict)
    regions = [raw] if was_dict else raw
    for item in items:
        _, city, cityId, region, token = CITY[item['city']]
        co = item['course']
        kw = co.pop('_photo_kw')
        photo, title = photo_of(kw, token)
        co['photo'] = photo
        co['photoTitle'] = title or kw
        co['photoLicense'] = LICENSE if photo else None
        time.sleep(0.1)
        # 도시 객체 찾거나 생성
        cityObj = next((r for r in regions if r.get('cityId') == cityId), None)
        if cityObj is None:
            cityObj = dict(city=city, cityId=cityId, region=region, courses=[])
            regions.append(cityObj)
        if any(c['id'] == co['id'] for c in cityObj['courses']):
            print(f"  건너뜀(이미 있음): {co['id']}")
            continue
        cityObj['courses'].append(co)
        added += 1
        print(f"  + {co['id']} ({city}) photo={'O' if photo else '-'}")
    out = regions[0] if was_dict else regions
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1))
    print(f"{fname} 저장")

