def clean(text: str) -> str:
    text = " ".join(text.split())
    for before, after in REPLACEMENTS.items():
        text = text.replace(before, after)
    return text


def trim(text: str, sentences: int = 2) -> str:
    parts = [part for part in re.split(r"(?<=[.!?])\s+", clean(text)) if part]
    return " ".join(parts[:sentences])


def regions(document):
    return document if isinstance(document, list) else [document]


def clean_course(course: dict) -> None:
    for field in ("headline", "subhead"):
        if course.get(field):
            course[field] = clean(course[field])
    for field in ("body", "deep", "ops", "unsure"):
        course[field] = [clean(item) for item in course.get(field, [])]
    for poi in course.get("poi", []):
        if poi.get("d"):
            poi["d"] = clean(poi["d"])
    for checkpoint in course.get("checkpoints", []):
        if checkpoint.get("description"):
            checkpoint["description"] = clean(checkpoint["description"])


def markdown(region: dict) -> str:
    lines = [f"# {region['city']} 러닝 코스", ""]
    for course in region["courses"]:
        lines += [
            "---", "", f"![{course['n']}](images/{course['id']}_hero.png)", "",
            f"`러닝 코스 · {region['city']}`", "", f"# {course['headline']}", "",
            course["subhead"], "", f"`{course['km']}km` `{course['min']}분` `{course['lv']}` `{course['mood']}`", "",
            f"[**지도에서 출발점 열기**  →](https://map.kakao.com/?q={course['n'].split()[0]})", "",
            "### 어떤 길인지", "",
        ]
        lines += [paragraph + "\n" for paragraph in course["body"]]
        lines += ["### 더 알아두면 좋은 것", ""] + [paragraph + "\n" for paragraph in course["deep"]]
        lines += ["### 가기 전에 알아두면 좋아요", ""] + [f"- {paragraph}" for paragraph in course["ops"]] + [""]
        if course.get("sources"):
            lines += ["### 확인한 자료", ""]
            lines += [f"- [{source['title']}]({source['url']}) · {source['type']} · {source['checkedAt']}" for source in course["sources"]]
            lines += [""]
        lines += ["### 지나는 곳", "", "| | 장소 |", "|---|---|"]
        for poi in course.get("poi", []):
            image = f'<img src="images/{poi["_img"]}_thumb.png" width="52">' if poi.get("_img") else "—"
            lines.append(f"| {image} | **{poi['n']}** — {poi['d']} |")
        lines += [""]
    return "\n".join(lines)


def main() -> None:
    paths = sorted(DATA.glob("*.json"))
    # 현재 원본의 큰 구성과 코스별 주제를 보존한 채 사실 수정, 출처, 실제 러너 문단을
    # 얹는다. 같은 문단은 다시 넣지 않으므로 반복 실행해도 결과가 불어나지 않는다.
    documents = [(path, json.loads(path.read_text())) for path in paths]
    found: set[str] = set()

    for _, document in documents:
        for region in regions(document):
            for course in region["courses"]:
                course_id = course["id"]
                if course_id not in COPY:
                    raise SystemExit(f"편집 원고 누락: {course_id}")
                found.add(course_id)
                headline, subhead, runner_note = COPY[course_id]
                clean_course(course)
                if course_id in TITLE_OVERRIDES:
                    course["headline"], course["subhead"] = TITLE_OVERRIDES[course_id]

                if course_id == "daegu-jinbatgol-uphill":
                    course["body"][2] = (
                        "숲 안으로 들어갈수록 차 소리는 멀어지고 호흡만 가까워진다. "
                        "용지봉 쪽 능선이 보이기 시작하면 고도가 쌓였다는 감각도 선명해진다."
                    )
                    course["deep"][0] = (
                        "진밭골 공영주차장을 출발점으로 삼을 수 있다. 첫 방문에는 한 번만 올라 "
                        "같은 길로 내려오며 경사와 노면을 익히는 편이 낫다."
                    )

                # 장소의 유래·풍경·동선은 그대로 둔다. 검색에서 얻은 러너의 감각은
                # 본문 결말 바로 앞에 한 문단만 더해 정보글처럼 기울지 않게 한다.
                body = list(course.get("body", []))
                if runner_note not in body:
                    insert_at = max(1, len(body) - 1)
                    body.insert(insert_at, runner_note)
                course["body"] = body

                source_rows = list(SOURCES.get(course_id, []))
                if "러닝갤" in course.get("src", "") and COMMUNITY_INDEX not in source_rows:
                    source_rows.append(COMMUNITY_INDEX)
                if source_rows:
                    course["sources"] = [
                        {"title": title, "url": url, "type": source_type, "checkedAt": CHECKED_AT}
                        for title, url, source_type in source_rows
                    ]

    missing = set(COPY) - found
    if missing:
        raise SystemExit(f"원본에 없는 편집 id: {sorted(missing)}")
    if len(found) != 64:
        raise SystemExit(f"코스 수 불일치: {len(found)}")

    for path, document in documents:
        path.write_text(json.dumps(document, ensure_ascii=False, indent=1) + "\n")

    all_courses = []
    for _, document in documents:
        for region in regions(document):
            for course in region["courses"]:
                all_courses.append(dict(course, city=region["city"], cityId=region["cityId"], region=region["region"]))
            (ROOT / f"{region['cityId']}.md").write_text(markdown(region))

    rendered = json.dumps(all_courses, ensure_ascii=False, indent=1) + "\n"
    (ROOT / "courses.json").write_text(rendered)
    SERVER.write_text(rendered)
    print(f"코스 {len(all_courses)}개 원고 편집 및 산출물 동기화 완료")


